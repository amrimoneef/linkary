enum VoiceIntentType {
  query,          // للاستعلام (مثل كم الجهاز متصل)
  action,         // للإجراءات (مثل إيقاف الجهاز، إعادة تشغيل)
  navigate,       // للتنقل (مثل افتح الإعدادات)
  needsMoreInfo,  // بحاجة لتبديل (مثل أي جهاز تريد حظره؟)
  ambiguous,      // تعارض (هل تقصد X أو Y؟)
  unknown,        // غير معروف
}
