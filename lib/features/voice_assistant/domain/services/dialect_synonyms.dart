  /// استبدال كل المرادفات بالشكل الأساسي الموحد مع معالجة اللهجات والهمزات
  static String unifyDialects(String text) {
    var result = text.trim();

    // 1. توحيد الأحرف المتشابهة (Normalisation)
    result = result.replaceAll('أ', 'ا')
                   .replaceAll('إ', 'ا')
                   .replaceAll('آ', 'ا')
                   .replaceAll('ة', 'ه')
                   .replaceAll('ى', 'ي')
                   .replaceAll('ؤ', 'و')
                   .replaceAll('ئ', 'ي');

    // 2. معالجة "ال" التعريف الزائدة (تبسيطاً)
    result = result.split(' ').map((word) {
      if (word.startsWith('ال') && word.length > 4) {
        return word.substring(2);
      }
      return word;
    }).join(' ');

    // 3. توحيد الكلمات بناءً على القاموس
    for (final entry in synonyms.entries) {
      final key = entry.key;
      for (final synonym in entry.value) {
        final normalizedSynonym = _normalize(synonym);

        if (result == normalizedSynonym) {
          result = key;
        } else {
          result = result.replaceAll(' $normalizedSynonym ', ' $key ');

          if (result.startsWith('$normalizedSynonym ')) {
            result = result.replaceFirst('$normalizedSynonym ', '$key ');
          }
          if (result.endsWith(' $normalizedSynonym')) {
            result = '${result.substring(0, result.length - normalizedSynonym.length)}$key';
          }
        }
      }
    }
    return result;
  }

  static String _normalize(String s) {
    return s.replaceAll('ة', 'ه')
            .replaceAll('ى', 'ي')
            .replaceAll('أ', 'ا')
            .replaceAll('إ', 'ا')
            .replaceAll('آ', 'ا')
            .replaceAll('ؤ', 'و')
            .replaceAll('ئ', 'ي');
  }
